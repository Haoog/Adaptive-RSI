function t(text){ return language === 'en' ? (english[text] ?? text) : text; }
const staticText = [], staticAttributes = [];
const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
while(walker.nextNode()){
 const node=walker.currentNode, key=node.textContent.trim();
 if(Object.hasOwn(english,key))staticText.push([node,node.textContent,key]);
}
for(const node of document.querySelectorAll('[aria-label], [placeholder]')){
 for(const attr of ['aria-label','placeholder']){
  const key=node.getAttribute(attr);
  if(Object.hasOwn(english,key))staticAttributes.push([node,attr,key]);
 }
}
function translateStatic(){
 document.documentElement.lang=language;
 for(const [node,original,key] of staticText){
  if(node.isConnected)node.textContent=language==='en'?original.replace(key,t(key)):original;
 }
 for(const [node,attr,key] of staticAttributes)if(node.isConnected)node.setAttribute(attr,t(key));
 document.querySelector('#language-select').value=language;
}
